"""
Run the full Black-76 benchmark, regenerate bench_chart.{html,png}, and
replace the auto-generated table block in README.md.

Run: uv run python benchmarks/update_readme.py
"""
import re
import sys
from pathlib import Path

from bench_chart import collect, render

REPO_ROOT = Path(__file__).resolve().parent.parent
README = REPO_ROOT / "README.md"
PNG_REL = "benchmarks/bench_chart.png"
HTML_REL = "benchmarks/bench_chart.html"

START = "<!-- BENCH:START - auto-generated by `task bench:readme`, do not edit -->"
END = "<!-- BENCH:END -->"

ORDERED = [
    "Python — pure (math.erf)",
    "Python — numpy/scipy",
    "Python — py_vollib",
    "Python — ngv_opx (single)",
    "Python — ngv_opx (vectorized)",
    "JavaScript — @ngv/opx (single)",
    "JavaScript — @ngv/opx (vectorized)",
    "Rust — ngv_opx (vectorized)",
]

COL_HEADERS = [
    "Python pure",
    "numpy/scipy",
    "py_vollib",
    "ngv_opx (single)",
    "**ngv_opx (vec)**",
    "JS @ngv/opx (single)",
    "**JS @ngv/opx (vec)**",
    "**Rust ngv_opx**",
]


def fmt(v: float) -> str:
    if v is None:
        return "—"
    return f"{v:,.1f}"


def build_block(paths) -> str:
    sizes = sorted({n for by_n in paths.values() for n in by_n.keys()})
    pyver = f"{sys.version_info.major}.{sys.version_info.minor}.{sys.version_info.micro}"

    header = "| N | " + " | ".join(COL_HEADERS) + " |"
    align = "|---:|" + "---:|" * len(COL_HEADERS)
    rows = []
    for n in sizes:
        cells = [f"{n:,}"] + [fmt(paths[name].get(n)) for name in ORDERED]
        rows.append("| " + " | ".join(cells) + " |")

    return "\n".join([
        START,
        "",
        f"![Black-76 throughput]({PNG_REL})",
        "",
        f"Per-option time in nanoseconds (lower is faster). Measured on Python {pyver}.",
        "",
        header,
        align,
        *rows,
        "",
        f"Interactive version: [`{HTML_REL}`]({HTML_REL}) (open locally; GitHub doesn't render embedded JS).",
        "",
        "Regenerate with `task bench:readme`.",
        "",
        END,
    ])


def update_readme(block: str) -> None:
    text = README.read_text()
    pattern = re.compile(
        re.escape(START) + r".*?" + re.escape(END),
        re.DOTALL,
    )
    if not pattern.search(text):
        raise SystemExit(
            f"sentinel block not found in {README}; expected lines:\n  {START}\n  {END}"
        )
    new_text = pattern.sub(block, text)
    README.write_text(new_text)


if __name__ == "__main__":
    print("collecting benchmarks...")
    paths = collect()
    out = render(paths)
    print(f"wrote {out} and {out.with_suffix('.png')}")
    block = build_block(paths)
    update_readme(block)
    print(f"updated {README}")
