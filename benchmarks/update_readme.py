"""
Run the full Black-76 benchmark, regenerate bench_chart.{html,png}, and
replace the auto-generated table block in README.md.

Run: uv run python benchmarks/update_readme.py
"""
import re
import sys
from pathlib import Path

from bench_chart import collect, render

REPO_ROOT = Path(__file__).resolve().parent.parent
README = REPO_ROOT / "README.md"
PNG_REL = "benchmarks/bench_chart.png"
HTML_REL = "benchmarks/bench_chart.html"

START = "<!-- BENCH:START - auto-generated by `task bench:readme`, do not edit -->"
END = "<!-- BENCH:END -->"

# Mirror bench_chart.py's column order exactly. Each entry carries the three
# pieces the stacked header surfaces: language / library / variant. The
# `highlight` flag bolds the column to draw the eye to the production ngv_opx
# rows (Python vec, JS vec, Rust vec).
COLUMNS = [
    ("Python — pure (math.erf)",          "PYTHON",     "math.erf",   "single",     False),
    ("Python — numpy/scipy",              "PYTHON",     "numpy/scipy","vectorized", False),
    ("Python — py_vollib",                "PYTHON",     "py_vollib",  "single",     False),
    ("Python — ngv_opx (single)",         "PYTHON",     "ngv_opx",    "single",     False),
    ("Python — ngv_opx (vectorized)",     "PYTHON",     "ngv_opx",    "vectorized", True),
    ("JavaScript — @westonplatter/ngv-opx (single)",    "JAVASCRIPT", "@westonplatter/ngv-opx",   "single",     False),
    ("JavaScript — @westonplatter/ngv-opx (vectorized)","JAVASCRIPT", "@westonplatter/ngv-opx",   "vectorized", True),
    ("Rust — ngv_opx (vectorized)",       "RUST",       "ngv_opx",    "vectorized", True),
]


def fmt(v: float) -> str:
    if v is None:
        return "—"
    return f"{v:,.1f}"


def _language_groups():
    """Yield (language, colspan) pairs in column order — collapses runs of
    the same language for the top-level grouped header row."""
    groups = []
    for _, lang, _, _, _ in COLUMNS:
        if groups and groups[-1][0] == lang:
            groups[-1] = (lang, groups[-1][1] + 1)
        else:
            groups.append((lang, 1))
    return groups


def build_html_table(paths) -> str:
    sizes = sorted({n for by_n in paths.values() for n in by_n.keys()})

    # Header row 1: language groups, with colspan across consecutive columns
    # that share the same language. Top-left N cell rowspans the full header
    # stack so the three header rows align cleanly.
    lang_cells = []
    for lang, span in _language_groups():
        lang_cells.append(
            f'      <th align="center" colspan="{span}">{lang}</th>'
        )
    # N spans all 4 header rows (language / library / variant / unit) so the
    # left column lines up cleanly with the data rows below it.
    row1 = (
        '    <tr>\n'
        '      <th rowspan="4" align="right">N</th>\n'
        + "\n".join(lang_cells)
        + "\n    </tr>"
    )

    # Header row 2: library name. Bold for highlighted (ngv_opx production)
    # columns so the eye lands on them first.
    lib_cells = []
    for _, _, lib, _, hi in COLUMNS:
        tag = f"<b>{lib}</b>" if hi else lib
        lib_cells.append(f'      <th align="center">{tag}</th>')
    row2 = "    <tr>\n" + "\n".join(lib_cells) + "\n    </tr>"

    # Header row 3: variant (single / vectorized).
    var_cells = []
    for _, _, _, var, hi in COLUMNS:
        tag = f"<b>{var}</b>" if hi else var
        var_cells.append(f'      <th align="center"><sub>{tag}</sub></th>')
    row3 = "    <tr>\n" + "\n".join(var_cells) + "\n    </tr>"

    # Header row 4: unit. Every data cell below is per-option time in
    # nanoseconds; surfacing the unit inside the table itself means readers
    # don't have to scroll back to the prose to remember what "829.2" means.
    unit_cells = [
        '      <th align="center"><sub><i>ns / option</i></sub></th>'
    ] * len(COLUMNS)
    row4 = "    <tr>\n" + "\n".join(unit_cells) + "\n    </tr>"

    # Data rows.
    data_rows = []
    for n in sizes:
        cells = [f'      <td align="right">{n:,}</td>']
        for name, _, _, _, hi in COLUMNS:
            v = fmt(paths[name].get(n))
            tag = f"<b>{v}</b>" if hi else v
            cells.append(f'      <td align="right">{tag}</td>')
        data_rows.append("    <tr>\n" + "\n".join(cells) + "\n    </tr>")

    return "\n".join([
        "<table>",
        "  <thead>",
        row1,
        row2,
        row3,
        row4,
        "  </thead>",
        "  <tbody>",
        *data_rows,
        "  </tbody>",
        "</table>",
    ])


def build_block(paths) -> str:
    pyver = f"{sys.version_info.major}.{sys.version_info.minor}.{sys.version_info.micro}"
    table = build_html_table(paths)
    return "\n".join([
        START,
        "",
        f"**All values are per-option time in nanoseconds (ns)** — lower is faster. "
        f"Measured on Python {pyver}.",
        f"Header reads top-to-bottom as **language → library → call shape → unit**, "
        f"matching `{HTML_REL}`. **Bold** marks the production `ngv_opx` paths.",
        "",
        table,
        "",
        f"Interactive chart: [`{HTML_REL}`]({HTML_REL}) (open locally; GitHub doesn't render embedded JS). "
        f"Static image: [`{PNG_REL}`]({PNG_REL}).",
        "",
        "Regenerate with `task bench:readme`.",
        "",
        END,
    ])


def update_readme(block: str) -> None:
    text = README.read_text()
    pattern = re.compile(
        re.escape(START) + r".*?" + re.escape(END),
        re.DOTALL,
    )
    if not pattern.search(text):
        raise SystemExit(
            f"sentinel block not found in {README}; expected lines:\n  {START}\n  {END}"
        )
    new_text = pattern.sub(block, text)
    README.write_text(new_text)


if __name__ == "__main__":
    print("collecting benchmarks...")
    paths = collect()
    out = render(paths)
    print(f"wrote {out} and {out.with_suffix('.png')}")
    block = build_block(paths)
    update_readme(block)
    print(f"updated {README}")
